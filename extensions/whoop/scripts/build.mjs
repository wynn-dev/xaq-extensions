// Bundles src/server.ts (with the MCP SDK and zod) into ONE self-contained ESM file, dist/server.mjs: no
// node_modules at run time, no install scripts. `--check` rebuilds in memory and fails if the committed dist differs
// (CI runs it). Run from the repo root after `npm ci`: `npm run build`.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const outfile = `${root}dist/server.mjs`;
const check = process.argv.includes("--check");
const sdkVersion = JSON.parse(readFileSync(new URL("../../../node_modules/@modelcontextprotocol/sdk/package.json", import.meta.url), "utf8")).version;
const zodVersion = JSON.parse(readFileSync(new URL("../../../node_modules/zod/package.json", import.meta.url), "utf8")).version;

const banner = [
  "// xaq WHOOP extension: GENERATED by extensions/whoop/scripts/build.mjs from extensions/whoop/src. Do not edit.",
  `// Bundles @modelcontextprotocol/sdk ${sdkVersion} (MIT), zod ${zodVersion} (MIT) and their dependencies; see NOTICE.`,
  'import { createRequire as __xaqCreateRequire } from "node:module";',
  "const require = __xaqCreateRequire(import.meta.url);",
].join("\n");

const result = await build({
  entryPoints: [`${root}src/server.ts`],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22.13",
  write: false,
  outfile,
  banner: { js: banner },
  legalComments: "eof",
  charset: "utf8",
  sourcemap: false,
  minify: false,
  logLevel: "warning",
  metafile: true,
});

const text = result.outputFiles[0].text;
const inputs = Object.keys(result.metafile.inputs).filter((p) => p.includes("node_modules/"));
const packages = [...new Set(inputs.map((p) => p.replace(/^.*node_modules\/((@[^/]+\/)?[^/]+).*$/, "$1")))].sort();

// THIRD_PARTY_LICENSES: each bundled package's own license file, verbatim.
const licensesFile = `${root}THIRD_PARTY_LICENSES`;
const licenses = [
  "Licenses of the third-party packages bundled into dist/server.mjs (generated by scripts/build.mjs).",
  ...packages.map((name) => {
    const dir = new URL(`../../../node_modules/${name}/`, import.meta.url);
    const pkg = JSON.parse(readFileSync(new URL("package.json", dir), "utf8"));
    const file = readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
    if (!file) throw new Error(`${name} ships no license file`);
    return `\n${"=".repeat(78)}\n${name}@${pkg.version} (${pkg.license})\n${"=".repeat(78)}\n\n${readFileSync(new URL(file, dir), "utf8").trim()}\n`;
  }),
].join("\n");

if (check) {
  let current = "";
  try {
    current = readFileSync(outfile, "utf8");
  } catch {
    // missing counts as stale
  }
  let currentLicenses = "";
  try {
    currentLicenses = readFileSync(licensesFile, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== text || currentLicenses !== licenses) {
    console.error("extensions/whoop/dist/server.mjs or THIRD_PARTY_LICENSES is out of date: run `npm run build` and commit both.");
    process.exit(1);
  }
  console.log(`dist is up to date (${(text.length / 1024).toFixed(0)} KiB; bundles ${packages.join(", ")})`);
} else {
  writeFileSync(outfile, text);
  writeFileSync(licensesFile, licenses);
  console.log(`wrote ${outfile} (${(text.length / 1024).toFixed(0)} KiB; bundles ${packages.join(", ")})`);
}
